"""Re-extract expert decisions into the v4 cache without re-solving the MILP.

The Path A epoch-deferral fix lives entirely in
``expert_dataset_generator.extract_expert_decisions``, which runs after the
anticipative MILP is solved. The v3 cache already stores each instance's MILP
solution (``milp_solution.completion_times`` and ``milp_solution.arc_solution``),
so the corrected expert decisions and trajectory can be regenerated by reusing
those stored solutions instead of calling ``solve_anticipative`` again. That
turns a ~16 hour re-solve into a few minutes of pure re-extraction.

This script reads every ``seed*.json`` under ``cache/training_set_il_v3/train``,
reconstructs an ``AnticipativeSolution`` from the stored MILP data, runs the
fixed ``extract_expert_decisions``, and writes a corrected record (identical to
the source except for ``expert_decisions`` and ``expert_trajectory``) to
``cache/training_set_il_v4/train``.

Run:
    PYTHONPATH=$PWD/src python scripts/experiments/reextract_decisions_v4.py
"""

from __future__ import annotations

import argparse
import json
import time
from datetime import datetime
from pathlib import Path

import numpy as np

from instances.synthetic_generator import SyntheticInstance
from anticipative.anticipative_milp import AnticipativeSolution
from training.expert_dataset_generator import extract_expert_decisions


REPO_ROOT = Path(__file__).resolve().parent.parent.parent
SRC_DIR = REPO_ROOT / "cache/training_set_il_v3/train"
DST_DIR = REPO_ROOT / "cache/training_set_il_v4/train"


def _travel(a: np.ndarray, b: np.ndarray, v: float) -> float:
    return float(np.linalg.norm(a - b) / v)


def reconstruct_solution(
    record: dict, instance: SyntheticInstance
) -> AnticipativeSolution:
    """Rebuild the AnticipativeSolution fields that extract_expert_decisions
    needs (completion_times and origin_to_pickup_travel) from cached MILP data.

    ``origin_to_pickup_travel`` is not stored directly; it is reconstructed from
    the arc solution exactly as ``anticipative_milp.solve_anticipative`` does:
    the origin of the arc reaching task j on robot r is the robot's initial
    position when the incoming arc starts at S_r, otherwise the drop location of
    the predecessor task i.
    """
    ms = record["milp_solution"]
    v = float(instance.config["v"])
    p0 = np.asarray(instance.initial_positions, dtype=np.float64)
    pickups = {int(t["id"]): np.asarray(t["pickup"], np.float64) for t in instance.tasks}
    drops = {int(t["id"]): np.asarray(t["drop"], np.float64) for t in instance.tasks}

    completion_times = {
        (int(c["r"]), int(c["j"])): float(c["f"]) for c in ms["completion_times"]
    }

    otp: dict = {}
    for arc in ms["arc_solution"]:
        r = int(arc["r"])
        i = str(arc["i"])
        j = str(arc["j"])
        if j.startswith("E"):  # arc into the robot's end node, not a task
            continue
        jt = int(j)
        origin = p0[r] if i.startswith("S") else drops[int(i)]
        otp[(r, jt)] = _travel(origin, pickups[jt], v)

    # Every served (r, j) must have an origin-to-pickup entry, or the extractor would KeyError; surface that as a clear failure instead.
    missing = [rj for rj in completion_times if rj not in otp]
    if missing:
        raise ValueError(
            f"missing origin_to_pickup_travel for {len(missing)} served pairs "
            f"(e.g. {missing[0]}); arc solution may be incomplete"
        )

    return AnticipativeSolution(
        objective_value=float(ms["objective_value"]),
        distance=float(ms["distance"]),
        makespan=float(ms["makespan"]),
        imbalance=float(ms["imbalance"]),
        arc_solution={},
        completion_times=completion_times,
        origin_to_pickup_travel=otp,
        solve_time_seconds=float(ms["solve_time_seconds"]),
        mip_gap=float(ms["mip_gap"]),
        status=str(ms["status"]),
        n_unserved_tasks=int(ms["n_unserved_tasks"]),
        obj_bound=float(ms.get("obj_bound", 0.0)),
    )


def reextract_one(record: dict) -> dict:
    """Return a corrected record with re-extracted decisions and trajectory."""
    instance = SyntheticInstance.from_dict(record["instance"])
    solution = reconstruct_solution(record, instance)
    expert_decisions, expert_trajectory = extract_expert_decisions(
        instance, solution
    )

    new_record = dict(record)  # shallow copy preserves every untouched field
    new_record["expert_decisions"] = [
        [[int(r), int(j)] for (r, j) in epoch_commits]
        for epoch_commits in expert_decisions
    ]
    new_record["expert_trajectory"] = expert_trajectory
    new_record["reextracted_from"] = "cache/training_set_il_v3"
    new_record["reextraction_timestamp"] = datetime.utcnow().isoformat()
    return new_record


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Re-extract v4 expert decisions from the cached v3 MILP "
        "solutions without re-solving. Refuses to overwrite a non-empty "
        "destination unless --force is given."
    )
    parser.add_argument(
        "--src", type=Path, default=SRC_DIR,
        help="Source cache directory of v3 records (default: %(default)s).",
    )
    parser.add_argument(
        "--dst", type=Path, default=DST_DIR,
        help="Destination directory for v4 records (default: %(default)s).",
    )
    parser.add_argument(
        "--force", action="store_true", default=False,
        help="Overwrite an existing non-empty destination directory.",
    )
    args = parser.parse_args()

    src_dir = args.src
    dst_dir = args.dst
    if not src_dir.exists():
        raise SystemExit(f"Source directory not found: {src_dir}")
    if dst_dir.exists() and any(dst_dir.glob("seed*.json")) and not args.force:
        raise SystemExit(
            f"Destination {dst_dir} already contains records. These may be "
            f"the labels a trained checkpoint was produced from. Pass --force "
            f"to overwrite them."
        )
    dst_dir.mkdir(parents=True, exist_ok=True)

    src_files = sorted(src_dir.glob("seed*.json"))
    print(f"Re-extracting {len(src_files)} records: {src_dir} -> {dst_dir}", flush=True)

    t0 = time.time()
    n_ok = 0
    n_fail = 0
    failures: list = []
    for i, fp in enumerate(src_files, 1):
        try:
            with fp.open("r") as f:
                record = json.load(f)
            new_record = reextract_one(record)
            with (dst_dir / fp.name).open("w") as f:
                json.dump(new_record, f, indent=2)
            n_ok += 1
        except Exception as exc:  # noqa: BLE001 - report and continue
            n_fail += 1
            failures.append((fp.name, repr(exc)))
            print(f"  FAILED {fp.name}: {exc}", flush=True)
        if i % 100 == 0:
            elapsed = time.time() - t0
            print(
                f"  {i}/{len(src_files)} done "
                f"({elapsed:.1f}s, {elapsed / i * 1000:.1f} ms/record)",
                flush=True,
            )

    elapsed = time.time() - t0
    print(
        f"\nDone in {elapsed:.1f}s. ok={n_ok} failed={n_fail} "
        f"({elapsed / max(1, len(src_files)) * 1000:.1f} ms/record)",
        flush=True,
    )
    if failures:
        print(f"{len(failures)} failures:", flush=True)
        for name, err in failures[:20]:
            print(f"  {name}: {err}", flush=True)


if __name__ == "__main__":
    main()
